const greetUserArrow = (name, timeOfDay) => { // name and timeOfDay are parameters that will be passed in when the function is called
    console.log(`Good ${timeOfDay}, ${name}!`); // this will print "Good timeOfDay, name!" to the console
}

greetUserArrow("Brendan", "Morning"); // this will print "Good Morning, Brendan!" to the console
